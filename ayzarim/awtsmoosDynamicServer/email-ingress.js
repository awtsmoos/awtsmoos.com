const { TextDecoder } = require('util');
const vm = require('vm'); // For safe execution of user scripts

module.exports = async function ({ sender, recipients, data }) {
    try {
        var time = Date.now();

        // 1. Parse content
        var parsed = parseMime(data);
        var decodedFrom = decodeMimeHeader(parsed.headers['from'] || sender);
        var decodedSubject = decodeMimeHeader(parsed.subject);
        var { name, email } = parseFromHeader(decodedFrom);
        if(!email || email.indexOf("@") === -1) email = sender;
        var cleanSender = email.replace(/[<>]/g, "").trim().replace("@", "_at_");

        // 2. Process Content
        var html = stripHistory(parsed.html || "", "html");
        var text = stripHistory(parsed.text || "", "text");
        if (html && parsed.attachments.length > 0) {
            html = embedInlineImages(html, parsed.attachments);
        }
        if (!html && text) {
            html = `<div style="white-space: pre-wrap; font-family: sans-serif;">${escapeHtml(text)}</div>`;
        }

        // --- 3. INTELLIGENCE LAYER LOOP ---
        for (var r of recipients) {
            var cleanRecipient = r.replace("@", "_at_").replace(/[<>]/g, "");
            var settingsPath = `/social/aliases/${cleanRecipient.split('_at_')[0]}/emailSettings`;
            
            // Get User Settings
            var settings = await this.db.get(settingsPath) || { 
                approved: {}, 
                rules: [],
                customScript: ""
            };

            // A. GATEKEEPER (Message Requests)
            // If sender is NOT in approved list, mark as request and auto-reply
            var status = "inbox";
            
            // B"H - Check approved list with strict & loose matching
            // cleanSender is usually "bob_at_gmail.com"
            var isApproved = settings.approved && (
                settings.approved[cleanSender] || 
                settings.approved[cleanSender.toLowerCase()] ||
                settings.approved[cleanSender.split('_at_')[0]] // Check short alias
            );

            if (settings.gatekeeperMode && !isApproved) {
                status = "request";
                
                // Send "Pending Approval" Auto-Reply
                // Check loop protection (don't reply to bots/notifications)
                if (!isAutoGenerated(decodedFrom, decodedSubject)) {
                    console.log(`B"H - Sending Gatekeeper Reply to ${email}`);
                    await sendSystemReply(this, r, email, 
                        `B"H\nMessage Request Pending`,
                        `B"H\n\nShalom,\n\n${r} has yet to approve this message request. Your message has been queued.`
                    );
                }
            }

            // B. RULES ENGINE (No-Code & Low-Code)
            // Only run if not a request (or if you want rules to apply to requests too)
            if (status !== "request") {
                await runUserLogic(this, settings, { 
                    from: email, to: r, subject: decodedSubject, content: text 
                });
            }

            // C. SAVE TO DB
            var threadPath = `/emails/${cleanRecipient}/threads/${cleanSender}`;
            
            // We save a metadata flag "status" so the UI knows where to show it
            await this.db.appendToObj(threadPath, {
                key: time + "",
                value: {
                    id: `${cleanSender}:${time}`,
                    uid: time + "",
                    status: status, // "inbox" or "request"
                    subject: decodedSubject || "(No Subject)",
                    content: html, 
                    textContent: text,
                    snippet: text.substring(0, 100),
                    attachments: parsed.attachments.filter(a => !a.wasEmbedded),
                    from: decodedFrom,
                    fromName: name,
                    fromEmail: email,
                    correspondent: cleanSender,
                    time: time,
                    timeSent: time,
                    read: false,
                    direction: "incoming"
                }
            });
            
            // D. NOTIFY
            if (this.ws) {
                // The recipient 'r' is like "coby@awtsmoos.com".
                // We simplify this to "coby" for the socket target, 
                // but pass the Full ID in the logic just in case.
                
                var socketTarget = cleanRecipient; // e.g. coby_at_awtsmoos.com
                
                // If it's a local address, try the short name first
                if(r.includes("@awtsmoos.com")) {
                    socketTarget = r.split("@")[0];
                }

                this.ws.sendToAlias(socketTarget, {
                    type: 'NEW_MAIL',
                    message: {
                        id: `${cleanSender}:${time}`,
                        uid: time + "", 
                        from: decodedFrom,
                        fromName: name || email,
                        subject: decodedSubject,
                        status: status,
                        snippet: text.substring(0, 50) + "...",
                        content: html,
                        timeSent: time,
                        correspondent: cleanSender,
                        direction: "incoming"
                    }
                });
            }
        }
        console.log("B\"H - Processed Mail:", email);
    } catch ($) {
        console.log("Error ingress", $);
    }
}

// --- LOGIC HELPERS ---

async function sendSystemReply(ctx, fromAlias, toEmail, subject, body) {
    if (ctx.mail && ctx.mail.smtpClient) {
        // Create clean instance to avoid race conditions
        try {
            // Need to require the class constructor. 
            // Since we are in a module, we can access the global require if passed, 
            // or assume context has a factory. 
            // Ideally, we clone the smtpClient config.
            
            // Hack for now: use existing client but allow it to handle concurrency internally
            await ctx.mail.smtpClient.sendMail(`${fromAlias}@awtsmoos.com`, toEmail, subject, body);
        } catch(e) { console.error("AutoReply Fail", e); }
    }
}

async function runUserLogic(ctx, settings, msg) {
    try {
        // 1. STRUCTURED RULES ENGINE
        if (settings.rules && Array.isArray(settings.rules)) {
            for (let rule of settings.rules) {
                if (!rule.enabled) continue;

                let matchFound = false;
                let matchedKeyword = "";
                
                // Normalized content for searching
                const contentLower = msg.content.toLowerCase();
                const keywords = (rule.keywords || "").toLowerCase().split(',').map(k => k.trim()).filter(k=>k);

                // --- CHECK CONDITIONS ---
                if (rule.condition === 'contains_any') {
                    // Match if ANY keyword exists
                    const found = keywords.find(k => contentLower.includes(k));
                    if (found) { matchFound = true; matchedKeyword = found; }
                } 
                else if (rule.condition === 'contains_only') {
                    // Strict: Message must essentially BE the keywords (ignoring small noise)
                    // Logic: Remove all keywords from message, if remaining length is small (< 5 chars), it's a match
                    let clean = contentLower;
                    keywords.forEach(k => clean = clean.replace(k, ''));
                    if (clean.replace(/[^a-z0-9]/g, '').length < 5 && keywords.some(k => contentLower.includes(k))) {
                        matchFound = true; matchedKeyword = keywords[0];
                    }
                }
                else if (rule.condition === 'javascript') {
                    // Advanced: Condition is determined by a JS boolean expression
                    const sandbox = { msg, text: contentLower };
                    vm.createContext(sandbox);
                    // User script e.g.: "msg.subject.includes('Urgent') && text.length > 100"
                    try { matchFound = vm.runInContext(rule.customCondition, sandbox, { timeout: 500 }); } catch(e){}
                }

                // --- EXECUTE ACTION ---
                if (matchFound) {
                    let replyBody = "";

                    if (rule.actionType === 'javascript') {
                        // Advanced JS Action
                        const sandbox = { msg, matchedKeyword, reply: (t) => { replyBody = t; } };
                        vm.createContext(sandbox);
                        try { vm.runInContext(rule.replyScript, sandbox, { timeout: 500 }); } catch(e){}
                    } else {
                        // Text Action with Variable Injection ($Keyword+N)
                        replyBody = processReplyVariables(rule.replyText, matchedKeyword, msg.content);
                    }

                    if (replyBody) {
                        await sendSystemReply(ctx, msg.to, msg.from, "Re: " + msg.subject, replyBody);
                    }
                    
                    // Stop after first match? Usually yes to prevent spam.
                    break; 
                }
            }
        }

        // 2. GLOBAL CUSTOM SCRIPT 
        // (Advanced)
        if (settings.customScript) {
            const sandbox = {
                msg: msg,
                reply: (text) => sendSystemReply(ctx, msg.to, msg.from, "Re: " + msg.subject, text),
                console: { log: () => {} } // sandboxed console
            };
            vm.createContext(sandbox);
            vm.runInContext(settings.customScript, sandbox, { timeout: 1000 });
        }

    } catch(e) { console.log("User Logic Error:", e.message); }
}

// Helper: Handles "$Hi+2" logic
function processReplyVariables(template, keyword, fullText) {
    if(!template) return "";
    
    // Regex to find variables like $hi+2 or $keyword+1
    // We replace case-insensitive matches of the keyword variable
    
    return template.replace(/\$([a-zA-Z0-9]+)\+(\d+)/g, (match, key, offset) => {
        // 1. Find the position of the keyword in the actual text
        // If user wrote $keyword+N, we look for the 'matchedKeyword' in text.
        // If they wrote specific word $Coby+1, we look for 'Coby'.
        
        const targetWord = (key.toLowerCase() === "keyword") ? keyword : key.toLowerCase();
        const textWords = fullText.replace(/\n/g, " ").split(" ");
        
        // Find index of word containing the target
        const index = textWords.findIndex(w => w.toLowerCase().includes(targetWord));
        
        if (index === -1) return "[not found]";
        
        // Get the word N places away
        const targetIndex = index + parseInt(offset);
        if (targetIndex < textWords.length) {
            return textWords[targetIndex];
        }
        return "";
    });
}




 

function isAutoGenerated(from, subject) {
    return /no-?reply|daemon|notification|auto/i.test(from) || 
           /automatic reply|out of office/i.test(subject);
}

// --- CORE PARSER ---

function parseMime(raw) {
    // FIX: Split robustly on double newline (Windows \r\n\r\n OR Unix \n\n)
    const splitMatch = raw.match(/\r?\n\r?\n/);
    if (!splitMatch) {
        // Fallback if no body
        return { headers: parseHeaders(raw), text: "", html: "", attachments: [], subject: "" };
    }
    
    const splitIndex = splitMatch.index;
    const headerBlock = raw.substring(0, splitIndex);
    const bodyBlock = raw.substring(splitIndex + splitMatch[0].length);
    
    const headers = parseHeaders(headerBlock);
    const contentType = headers['content-type'] || 'text/plain';
    const encoding = headers['content-transfer-encoding'] || '';
    const subject = headers['subject'] || '';

    let result = { headers, text: "", html: "", attachments: [], subject };

    // 1. Multipart
    if (contentType.includes('multipart/')) {
        const boundaryMatch = contentType.match(/boundary="?([^";]+)"?/i);
        if (boundaryMatch) {
            const boundary = boundaryMatch[1];
            const parts = bodyBlock.split(`--${boundary}`);

            for (let part of parts) {
                if (part.trim() === '--' || part.trim() === '') continue;
                // Recursion
                const subParsed = parseMime(part.trimStart()); 
                
                if (subParsed.html) result.html += subParsed.html;
                if (subParsed.text) result.text += subParsed.text;
                result.attachments = result.attachments.concat(subParsed.attachments);
            }
        }
    } 
    // 2. HTML
    else if (contentType.includes('text/html')) {
        result.html = decodeBody(bodyBlock, encoding);
    } 
    // 3. Plain Text
    else if (contentType.includes('text/plain')) {
        result.text = decodeBody(bodyBlock, encoding);
    }
    // 4. Attachments
    else {
        const cidMatch = headers['content-id'];
        const filenameMatch = headers['content-disposition']?.match(/filename="?([^";]+)"?/i);
        const filename = filenameMatch ? filenameMatch[1] : 'unknown';
        
        // Remove newlines from base64 body
        let base64Data = bodyBlock.replace(/\r?\n/g, '');
        
        if(base64Data.length > 10) { 
            result.attachments.push({
                filename,
                contentType: contentType.split(';')[0],
                contentId: cidMatch ? cidMatch.trim() : null, 
                data: `data:${contentType.split(';')[0]};base64,${base64Data}`,
                wasEmbedded: false
            });
        }
    }

    return result;
}

// --- OTHER HELPERS ---

function embedInlineImages(html, attachments) {
    return html.replace(/src=["']cid:([^"']+)["']/gi, (match, cid) => {
        const found = attachments.find(a => 
            a.contentId === cid || a.contentId === `<${cid}>` || a.contentId.includes(cid)
        );
        if (found) {
            found.wasEmbedded = true;
            return `src="${found.data}"`;
        }
        return match;
    });
}

function parseHeaders(headerStr) {
    const headers = {};
    if (!headerStr) return headers;
    
    // Unfold headers (lines starting with space belong to previous line)
    const unfolded = headerStr.replace(/\r?\n[ \t]+/g, ' ');
    
    unfolded.split(/\r?\n/).forEach(line => {
        const index = line.indexOf(':');
        if (index > -1) {
            const key = line.substring(0, index).trim().toLowerCase();
            const val = line.substring(index + 1).trim();
            headers[key] = val;
        }
    });
    return headers;
}

function parseFromHeader(fromStr) {
    if(!fromStr) return { name: "", email: "" };
    
    fromStr = fromStr.trim();
    // Match "Name <email>"
    const complex = fromStr.match(/^(?:\"?([^"<]+)\"?\s*)?<(.*)>$/);
    if (complex) {
        return {
            name: (complex[1] || "").trim().replace(/"/g, ""), 
            email: (complex[2] || "").trim()
        };
    }
    // Match just "email" (fallback)
    return { name: "", email: fromStr };
}

function decodeBody(content, encoding) {
    if (!encoding) return content;
    encoding = encoding.toLowerCase().trim();
    if (encoding === 'base64') {
        return Buffer.from(content.replace(/\r?\n/g, ''), 'base64').toString('utf-8');
    } 
    if (encoding === 'quoted-printable') {
        return decodeQuotedPrintable(content);
    }
    return content;
}

function decodeQuotedPrintable(str) {
    // 1. Remove Soft Line breaks (=\r\n or =\n)
    let clean = str.replace(/=\r?\n/g, '');
    
    // 2. Decode Hex
    let bytes = [];
    for (let i = 0; i < clean.length; i++) {
        if (clean[i] === '=') {
            const hex = clean.substr(i + 1, 2);
            if (hex.match(/^[0-9A-F]{2}$/i)) {
                bytes.push(parseInt(hex, 16));
                i += 2;
                continue;
            }
        }
        bytes.push(clean.charCodeAt(i));
    }
    return Buffer.from(bytes).toString('utf-8');
}

// stripHistory logic from previous robust version...
function stripHistory(content, type) {
    if (!content) return "";
    
    if (type === "html") {
        var markers = [
            /<div [^>]*class=["'][^"']*gmail_quote[^"']*["'][^>]*>/i,
            /<div [^>]*class=["'][^"']*yahoo_quoted[^"']*["'][^>]*>/i,
            /<div [^>]*class=["'][^"']*protonmail_quote[^"']*["'][^>]*>/i,
            /<div [^>]*id=["']divRplyFwdMsg["'][^>]*>/i,
            /<div [^>]*class=["'][^"']*moz-cite-prefix[^"']*["'][^>]*>/i,
            /<div[^>]*>\s*On\s.{5,200}?\s*wrote:\s*<br>\s*<\/div>/i,
            /<hr[^>]*>\s*<div[^>]*>\s*<b>\s*From:\s*<\/b>/i
        ];

        for (var regex of markers) {
            var match = content.match(regex);
            if (match) {
                content = content.substring(0, match.index);
                content = content.replace(/(\s*<br\s*\/?>\s*)+$/i, '');
                return content.trim();
            }
        }
        return content.trim();
    } else {
        const lines = content.split(/\r?\n/);
        const cleanLines = [];
        for (let i = 0; i < lines.length; i++) {
            let line = lines[i];
            if (/^>?\s*On\s.+?wrote:$/i.test(line)) break;
            if (/^[\s-]*Original Message[\s-]*$/.test(line)) break;
            if (/^[\s-]*Forwarded Message[\s-]*$/.test(line)) break;
            if (/^From:\s/.test(line)) {
                var next = lines[i+1] || "";
                if (/^Sent:\s/.test(next) || /^Date:\s/.test(next) || /^To:\s/.test(next)) break;
            }
            if (line.trim() === '--') break; 
            cleanLines.push(line);
        }
        return cleanLines.join('\n').trim();
    }
}

function decodeMimeHeader(header) {
    if (!header) return "";
    return header.replace(/=\?([^?]+)\?([BQ])\?([^?]+)\?=/gi, (match, charset, encoding, text) => {
        try {
            if (encoding.toUpperCase() === 'B') {
                return Buffer.from(text, 'base64').toString('utf-8'); // Simplified to utf-8
            } else if (encoding.toUpperCase() === 'Q') {
                return text.replace(/_/g, ' ').replace(/=([0-9A-F]{2})/gi, (m, hex) => String.fromCharCode(parseInt(hex, 16)));
            }
        } catch (e) { return match; }
        return match;
    });
}

function escapeHtml(text) {
    return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}