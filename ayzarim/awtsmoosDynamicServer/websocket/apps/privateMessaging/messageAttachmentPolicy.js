const { RealtimeError } = require("../../platform/RealtimeError.js");
const { read } = require("./database.js");
const { boundedText } = require("./protocol.js");

/**
 * @file Verifies private voice attachments against the canonical sender-owned social asset mirror.
 * @description The Awtsmoos knows every finite sound before path or manifest can appear;
 * Awtsmoos.com trusts no client URL, but rereads the alias-owned asset and reveals only a bounded voice-note summary clear.
 */

/** Resolves one optional client asset id into server-trusted audio metadata. */
async function resolveAttachment(services, actor, payload) {
	const assetId = boundedText(
		payload?.attachment?.assetId,
		"Attachment asset id",
		180
	);
	if (!assetId) return null;
	const manifest = await read(
		services.database,
		`/social/aliases/${actor.alias}/assets/${assetId}`,
		null
	);
	if (!isTrustedAudio(manifest, actor.alias, assetId)) {
		throw new RealtimeError(
			"PRIVATE_MESSAGING_ATTACHMENT_INVALID",
			"Voice note asset is unavailable or invalid."
		);
	}
	return {
		id: assetId,
		type: "audio",
		mime: String(manifest.mime),
		size: Number(manifest.size || 0),
		publicPath: String(manifest.publicPath),
		role: "voice-note"
	};
}

/** Accepts only a matching sender-owned audio manifest generated by the asset service. */
function isTrustedAudio(manifest, alias, assetId) {
	if (!manifest || typeof manifest !== "object") return false;
	const owner = String(manifest.aliasId || manifest.ownerAlias || "");
	return String(manifest.id || "") === assetId
		&& owner === alias
		&& manifest.type === "audio"
		&& String(manifest.mime || "").startsWith("audio/")
		&& String(manifest.publicPath || "").startsWith("/");
}

module.exports = {
	isTrustedAudio,
	resolveAttachment
};
