const { TextDecoder } = require('util');
const vm = require('vm');
// B"H - Import Shared Rules Logic
const rulesEngine = require('./awtsmoosEmailRules.js');

module.exports = async function ({ sender, recipients, data }) {
    try {
        var time = Date.now();
        var parsed = parseMime(data);
        var decodedFrom = decodeMimeHeader(parsed.headers['from'] || sender);
        var decodedSubject = decodeMimeHeader(parsed.subject);
        var { name, email } = parseFromHeader(decodedFrom);
        if(!email || email.indexOf("@") === -1) email = sender;
        var cleanSender = email.replace(/[<>]/g, "").trim().replace("@", "_at_");

        var html = stripHistory(parsed.html || "", "html");
        var text = stripHistory(parsed.text || "", "text");
        if (html && parsed.attachments.length > 0) {
            html = embedInlineImages(html, parsed.attachments);
        }
        if (!html && text) {
            html = `<div style="white-space: pre-wrap; font-family: sans-serif;">${escapeHtml(text)}</div>`;
        }

        for (var r of recipients) {
            var rawEmail = r.replace(/[<>]/g, "").trim(); 
            var cleanRecipient = rawEmail.replace("@", "_at_");
            var settingsPath = `/social/aliases/${cleanRecipient.split('_at_')[0]}/emailSettings`;
            
            var settings = await this.db.get(settingsPath) || { approved: {}, rules: [], customScript: "" };

            var status = "inbox";
            var isApproved = settings.approved && (
                settings.approved[cleanSender] || 
                settings.approved[cleanSender.toLowerCase()] ||
                settings.approved[cleanSender.split('_at_')[0]]
            );

            if (settings.gatekeeperMode && !isApproved) {
                status = "request";
                if (!isAutoGenerated(decodedFrom, decodedSubject)) {
                    await sendSystemReply(this, r, email, `B"H\nMessage Request Pending`,
                        `B"H\n\nShalom,\n\n${r} has yet to approve this message request. Your message has been queued.`
                    );
                }
            }

            // B"H - NEW RULES IMPLEMENTATION
            if (status !== "request" && !isAutoGenerated(decodedFrom, decodedSubject)) {
                // We use the shared engine, passing context for AI and Reply
                await rulesEngine.processRules({
                    settings,
                    msg: { from: email, to: r, subject: decodedSubject, content: text },
                    dependencies: {
                        // Pass the server's AI method (from index.js injection logic)
                        callGemini: this.callGemini ? this.callGemini.bind(this) : null,
                        reply: (replyText) => sendSystemReply(this, r, email, "Re: " + decodedSubject, replyText),
                        console: console
                    }
                });
                
                // Keep Legacy Global Script support (Separate from Rules)
                if (settings.customScript) {
                     const sandbox = {
                        msg: { from: email, to: r, subject: decodedSubject, content: text },
                        reply: (t) => sendSystemReply(this, r, email, "Re: " + decodedSubject, t),
                        console: { log: () => {} }
                    };
                    vm.createContext(sandbox);
                    try { vm.runInContext(settings.customScript, sandbox, { timeout: 1000 }); } catch(e){}
                }
            }

            // SAVE TO DB
            var threadPath = `/emails/${cleanRecipient}/threads/${cleanSender}`;
            await this.db.appendToObj(threadPath, {
                key: time + "",
                value: {
                    id: `${cleanSender}:${time}`,
                    uid: time + "",
                    messageId: parsed.headers['message-id'] || null,
                    status: status,
                    subject: decodedSubject || "(No Subject)",
                    content: html, 
                    textContent: text,
                    snippet: text.substring(0, 100),
                    attachments: parsed.attachments.filter(a => !a.wasEmbedded),
                    from: decodedFrom, fromName: name, fromEmail: email, correspondent: cleanSender,
                    time: time, timeSent: time, read: false, direction: "incoming"
                }
            });
            
            // NOTIFY SOCKET
            if (this.ws) {
                var socketTarget = cleanRecipient.endsWith("_at_awtsmoos.com") ? cleanRecipient.split("_at_")[0] : cleanRecipient; 
                this.ws.sendToAlias(socketTarget, {
                    type: 'NEW_MAIL',
                    message: {
                        id: `${cleanSender}:${time}`,
                        uid: time + "", 
                        from: decodedFrom, fromName: name || email, subject: decodedSubject, status: status,
                        snippet: text.substring(0, 50) + "...", content: html, timeSent: time,
                        correspondent: cleanSender, direction: "incoming"
                    }
                });
            }
        }
    } catch ($) { console.log("Error ingress", $); }
}

async function sendSystemReply(ctx, fromAlias, toEmail, subject, body) {
    if (ctx.mail && ctx.mail.smtpClient) {
        try { await ctx.mail.smtpClient.sendMail(`${fromAlias}@awtsmoos.com`, toEmail, subject, body); } 
        catch(e) { console.error("AutoReply Fail", e); }
    }
}

function isAutoGenerated(from, subject) {
    return /no-?reply|daemon|notification|auto/i.test(from) || /automatic reply|out of office/i.test(subject);
}

// --- CORE PARSER & HELPERS (Identical to previous, preserved for completeness) ---
function parseMime(raw) {
    const splitMatch = raw.match(/\r?\n\r?\n/);
    if (!splitMatch) return { headers: parseHeaders(raw), text: "", html: "", attachments: [], subject: "" };
    const splitIndex = splitMatch.index;
    const headerBlock = raw.substring(0, splitIndex);
    const bodyBlock = raw.substring(splitIndex + splitMatch[0].length);
    const headers = parseHeaders(headerBlock);
    const contentType = headers['content-type'] || 'text/plain';
    const encoding = headers['content-transfer-encoding'] || '';
    const subject = headers['subject'] || '';
    let result = { headers, text: "", html: "", attachments: [], subject };

    if (contentType.includes('multipart/')) {
        const boundaryMatch = contentType.match(/boundary="?([^";]+)"?/i);
        if (boundaryMatch) {
            const boundary = boundaryMatch[1];
            const parts = bodyBlock.split(`--${boundary}`);
            for (let part of parts) {
                if (part.trim() === '--' || part.trim() === '') continue;
                const subParsed = parseMime(part.trimStart()); 
                if (subParsed.html) result.html += subParsed.html;
                if (subParsed.text) result.text += subParsed.text;
                result.attachments = result.attachments.concat(subParsed.attachments);
            }
        }
    } else if (contentType.includes('text/html')) {
        result.html = decodeBody(bodyBlock, encoding);
    } else if (contentType.includes('text/plain')) {
        result.text = decodeBody(bodyBlock, encoding);
    } else {
        const filenameMatch = headers['content-disposition']?.match(/filename="?([^";]+)"?/i);
        let base64Data = bodyBlock.replace(/\r?\n/g, '');
        if(base64Data.length > 10) { 
            result.attachments.push({
                filename: filenameMatch ? filenameMatch[1] : 'unknown',
                contentType: contentType.split(';')[0],
                contentId: headers['content-id'] ? headers['content-id'].trim() : null, 
                data: `data:${contentType.split(';')[0]};base64,${base64Data}`,
                wasEmbedded: false
            });
        }
    }
    return result;
}
function embedInlineImages(html, attachments) {
    return html.replace(/src=["']cid:([^"']+)["']/gi, (match, cid) => {
        const found = attachments.find(a => a.contentId === cid || a.contentId === `<${cid}>` || a.contentId.includes(cid));
        if (found) { found.wasEmbedded = true; return `src="${found.data}"`; }
        return match;
    });
}
function parseHeaders(headerStr) {
    const headers = {};
    if (!headerStr) return headers;
    headerStr.replace(/\r?\n[ \t]+/g, ' ').split(/\r?\n/).forEach(line => {
        const index = line.indexOf(':');
        if (index > -1) headers[line.substring(0, index).trim().toLowerCase()] = line.substring(index + 1).trim();
    });
    return headers;
}
function parseFromHeader(fromStr) {
    if(!fromStr) return { name: "", email: "" };
    const complex = fromStr.trim().match(/^(?:\"?([^"<]+)\"?\s*)?<(.*)>$/);
    return complex ? { name: (complex[1]||"").trim().replace(/"/g,""), email: (complex[2]||"").trim() } : { name:"", email: fromStr.trim() };
}
function decodeBody(content, encoding) {
    if (!encoding) return content;
    if (encoding.toLowerCase().trim() === 'base64') return Buffer.from(content.replace(/\r?\n/g, ''), 'base64').toString('utf-8');
    if (encoding.toLowerCase().trim() === 'quoted-printable') return decodeQuotedPrintable(content);
    return content;
}
function decodeQuotedPrintable(str) {
    let clean = str.replace(/=\r?\n/g, '');
    let bytes = [];
    for (let i = 0; i < clean.length; i++) {
        if (clean[i] === '=') {
            const hex = clean.substr(i + 1, 2);
            if (hex.match(/^[0-9A-F]{2}$/i)) { bytes.push(parseInt(hex, 16)); i += 2; continue; }
        }
        bytes.push(clean.charCodeAt(i));
    }
    return Buffer.from(bytes).toString('utf-8');
}

function decodeMimeHeader(header) {
    if (!header) return "";
    return header.replace(/=\?([^?]+)\?([BQ])\?([^?]+)\?=/gi, (m, c, e, t) => {
        try { return e.toUpperCase() === 'B' ? Buffer.from(t, 'base64').toString('utf-8') : t.replace(/_/g, ' ').replace(/=([0-9A-F]{2})/gi, (m, h) => String.fromCharCode(parseInt(h, 16))); } catch (x) { return m; }
    });
}
function escapeHtml(text) { return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }

function stripHistory(content, type) {
    if (!content) return "";
    if (type === "html") {
        var markers = [/<div [^>]*class=["'][^"']*gmail_quote/i, /<div [^>]*class=["'][^"']*yahoo_quoted/i, /<div [^>]*id=["']divRplyFwdMsg/i, /<div[^>]*>\s*On\s.{5,200}?\s*wrote:\s*<br>/i];
        
        for (var regex of markers) {
        var match = content.match(regex); if (match) return content.substring(0, match.index).replace(/(\s*<br\s*\/?>\s*)+$/i, '').trim();
        }
        return content.trim();
    }
    return content.split(/\r?\n/).filter(line => !/^>?\s*On\s.+?wrote:$/i.test(line) && !/^[\s-]*Original Message/.test(line) && line.trim() !== '--').join('\n').trim();
}