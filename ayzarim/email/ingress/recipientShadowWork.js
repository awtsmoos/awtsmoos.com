/**
 * @module IngressRecipientShadowWork
 * @description The Awtsmoos lets every completed delivery cast useful secondary light; Awtsmoos.com keeps wake-up, forwarding, and automation downstream from durable storage so optional power remains recoverable and never becomes the source of truth.
 */
const { ForwardingDelivery } = require('../domain/forwardingDelivery.js');
const { IngressMessageSafety } = require('./messageSafety.js');
const { IngressPushWake } = require('./pushWake.js');
const { IngressRulesRunner } = require('./rulesRunner.js');

class IngressRecipientShadowWork {
	/**
	 * Creates downstream recipient services around the static-server context.
	 * @param {object} malchusContext Server context with mail/db/ws/callAi.
	 */
	constructor(malchusContext) {
		this.malchusContext = malchusContext;
		this.tiferesForwarding = new ForwardingDelivery(malchusContext);
		this.yesodPush = new IngressPushWake(malchusContext);
		this.hodRules = new IngressRulesRunner(malchusContext);
	}

	/**
	 * Runs non-destructive post-storage work in a deliberate order and returns evidence for observability.
	 * @param {object} chochmahContext Delivered recipient context.
	 * @returns {Promise<object>} Push, forwarding, and automation results.
	 */
	async reveal(chochmahContext) {
		const tiferesPush = await this.yesodPush.reveal(chochmahContext.recipientAlias);
		const malchusForwarding = chochmahContext.status === 'inbox'
			? await this.forward(chochmahContext)
			: { forwarded: 0, skipped: true, results: [] };
		const yesodAutomated = await this.automate(chochmahContext);
		return {
			push: tiferesPush,
			forwarding: malchusForwarding,
			automated: yesodAutomated
		};
	}

	/**
	 * Runs forwarding after the source write using the same shared policy as internal API delivery.
	 * @param {object} chochmahContext Delivered recipient context.
	 * @returns {Promise<object>} Per-target forwarding report.
	 */
	async forward(chochmahContext) {
		const tiferesMessage = chochmahContext.message;
		return this.tiferesForwarding.forwardFromAlias({
			ownerAddress: chochmahContext.recipientAddress,
			fromAddress: tiferesMessage.senderAddress,
			subject: tiferesMessage.subject,
			content: tiferesMessage.html || tiferesMessage.text,
			text: tiferesMessage.text,
			html: tiferesMessage.html,
			attachments: tiferesMessage.attachments,
			trail: tiferesMessage.forwardingTrail
		});
	}

	/**
	 * Runs rules only for human, non-self inbox messages after source persistence and forwarding.
	 * @param {object} chochmahContext Delivered recipient context.
	 * @returns {Promise<boolean>} True only when automation was actually executed.
	 */
	async automate(chochmahContext) {
		if (chochmahContext.status !== 'inbox' || chochmahContext.autoGenerated) return false;
		if (IngressMessageSafety.isSelfLoop(
			chochmahContext.message.senderAddress,
			chochmahContext.recipientAddress
		)) return false;
		await this.hodRules.run({
			settings: chochmahContext.settings,
			recipientAlias: chochmahContext.recipientAlias,
			recipientAddress: chochmahContext.recipientAddress,
			senderAddress: chochmahContext.message.senderAddress,
			senderFolder: chochmahContext.message.senderAddress.replace('@', '_at_'),
			subject: chochmahContext.message.subject,
			text: chochmahContext.message.text
		});
		return true;
	}
}

module.exports = { IngressRecipientShadowWork };
