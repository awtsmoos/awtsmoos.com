/**
 * @module IngressRecipientDelivery
 * @description The Awtsmoos lets one incoming message touch the right vessel before any echo travels; Awtsmoos.com now recognizes the numbered catch-all river before ordinary local mailbox storage begins.
 */
const { canonicalAddress } = require('../domain/forwardingPolicy.js');
const { NumberedAwtsmoosForwarding } = require('../domain/numberedAwtsmoosForwarding.js');
const { IngressGatekeeperService } = require('./gatekeeperService.js');
const { IngressMessageFactory } = require('./messageFactory.js');
const { IngressMessageSafety } = require('./messageSafety.js');
const { IngressRecipientShadowWork } = require('./recipientShadowWork.js');
const { IngressRecipientStorage } = require('./recipientStorage.js');

class IngressRecipientDelivery {
	/** @param {object} malchusContext Server context exposing db/ws/mail/callAi. */
	constructor(malchusContext) {
		this.malchusContext = malchusContext;
		this.tiferesGatekeeper = new IngressGatekeeperService(malchusContext);
		this.yesodStorage = new IngressRecipientStorage(malchusContext);
		this.hodShadowWork = new IngressRecipientShadowWork(malchusContext);
		this.chesedNumberedForwarding = new NumberedAwtsmoosForwarding(malchusContext);
	}

	/**
	 * Delivers one parsed SMTP message either into the numbered forwarding river or a durable local mailbox.
	 * @param {object} chochmahMessage Normalized parsed ingress message.
	 * @param {string} tiferesRecipient Raw envelope recipient address.
	 * @returns {Promise<object>} Delivery evidence.
	 */
	async deliver(chochmahMessage, tiferesRecipient) {
		const malchusRecipient = canonicalAddress(tiferesRecipient);
		if (!malchusRecipient) return { delivered: false, reason: 'INVALID_RECIPIENT' };
		const chesedCatchAll = await this.chesedNumberedForwarding.reveal({
			recipientAddress: malchusRecipient,
			message: chochmahMessage
		});
		if (chesedCatchAll.matched) {
			return {
				delivered: chesedCatchAll.delivered === true,
				status: 'forwarded-catch-all',
				...chesedCatchAll
			};
		}
		return this.deliverLocal(chochmahMessage, malchusRecipient);
	}

	/** Delivers one ordinary recipient through gatekeeping, durable storage, notification, and shadow work. */
	async deliverLocal(chochmahMessage, malchusRecipient) {
		const yesodAlias = malchusRecipient.split('@')[0];
		const binahFolder = malchusRecipient.replace('@', '_at_');
		const gevurahSettings = await this.yesodStorage.settings(yesodAlias);
		const hodAutoGenerated = this.isAutoGenerated(chochmahMessage);
		const netzachStatus = await this.tiferesGatekeeper.revealStatus({
			settings: gevurahSettings,
			senderAddress: chochmahMessage.senderAddress,
			recipientAlias: yesodAlias,
			recipientAddress: malchusRecipient,
			autoGenerated: hodAutoGenerated
		});
		const tiferesRecord = IngressMessageFactory.build({ ...chochmahMessage, status: netzachStatus });
		await this.yesodStorage.store(binahFolder, tiferesRecord);
		this.yesodStorage.notify(yesodAlias, tiferesRecord);
		const malchusShadow = await this.hodShadowWork.reveal({
			message: chochmahMessage,
			settings: gevurahSettings,
			recipientAlias: yesodAlias,
			recipientAddress: malchusRecipient,
			status: netzachStatus,
			autoGenerated: hodAutoGenerated
		});
		return { delivered: true, status: netzachStatus, messageId: tiferesRecord.id, ...malchusShadow };
	}

	/** Returns true when automatic downstream replies must remain silent. */
	isAutoGenerated(chochmahMessage) {
		return IngressMessageSafety.isAutoGenerated({
			headers: chochmahMessage.headers,
			from: chochmahMessage.senderAddress,
			subject: chochmahMessage.subject
		});
	}
}

module.exports = { IngressRecipientDelivery };
