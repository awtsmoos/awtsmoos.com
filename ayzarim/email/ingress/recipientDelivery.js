/**
 * @module IngressRecipientDelivery
 * @description The Awtsmoos lets one incoming message touch its true recipient before any shadow work unfolds; Awtsmoos.com stores first, signals second, forwards third, and automates last so advanced power never outruns durable truth.
 */
const { canonicalAddress } = require('../domain/forwardingPolicy.js');
const { ForwardingDelivery } = require('../domain/forwardingDelivery.js');
const { IngressGatekeeperService } = require('./gatekeeperService.js');
const { IngressMessageFactory } = require('./messageFactory.js');
const { IngressMessageSafety } = require('./messageSafety.js');
const { IngressPushWake } = require('./pushWake.js');
const { IngressRulesRunner } = require('./rulesRunner.js');

class IngressRecipientDelivery {
	/**
	 * Creates one recipient pipeline around the static-server context shared by SMTP ingress.
	 * @param {object} malchusContext Server context exposing db/ws/mail/callAi.
	 */
	constructor(malchusContext) {
		this.malchusContext = malchusContext;
		this.tiferesGatekeeper = new IngressGatekeeperService(malchusContext);
		this.yesodForwarding = new ForwardingDelivery(malchusContext);
		this.hodPush = new IngressPushWake(malchusContext);
		this.netzachRules = new IngressRulesRunner(malchusContext);
	}

	/**
	 * Delivers one already-parsed SMTP message to one local recipient, then performs non-destructive shadow work.
	 * @param {object} chochmahMessage Normalized parsed ingress message.
	 * @param {string} tiferesRecipient Raw envelope recipient address.
	 * @returns {Promise<object>} Delivery, forwarding, and automation evidence.
	 */
	async deliver(chochmahMessage, tiferesRecipient) {
		const malchusRecipient = canonicalAddress(tiferesRecipient);
		if (!malchusRecipient) return { delivered: false, reason: 'INVALID_RECIPIENT' };
		const yesodAlias = malchusRecipient.split('@')[0];
		const binahFolder = malchusRecipient.replace('@', '_at_');
		const gevurahSettings = await this.settings(yesodAlias);
		const hodAutoGenerated = IngressMessageSafety.isAutoGenerated({
			headers: chochmahMessage.headers,
			from: chochmahMessage.senderAddress,
			subject: chochmahMessage.subject
		});
		const netzachStatus = await this.tiferesGatekeeper.revealStatus({
			settings: gevurahSettings,
			senderAddress: chochmahMessage.senderAddress,
			recipientAlias: yesodAlias,
			recipientAddress: malchusRecipient,
			autoGenerated: hodAutoGenerated
		});
		const tiferesRecord = IngressMessageFactory.build({
			...chochmahMessage,
			status: netzachStatus
		});
		await this.store(binahFolder, tiferesRecord);
		this.notify(yesodAlias, tiferesRecord);
		const malchusWake = await this.hodPush.reveal(yesodAlias);
		const yesodForwarding = netzachStatus === 'inbox'
			? await this.forward(malchusRecipient, chochmahMessage)
			: { forwarded: 0, skipped: true, results: [] };
		const binahAutomated = await this.automate({
			message: chochmahMessage,
			settings: gevurahSettings,
			recipientAlias: yesodAlias,
			recipientAddress: malchusRecipient,
			status: netzachStatus,
			autoGenerated: hodAutoGenerated
		});
		return {
			delivered: true,
			status: netzachStatus,
			messageId: tiferesRecord.id,
			forwarding: yesodForwarding,
			push: malchusWake,
			automated: binahAutomated
		};
	}

	/** Reads alias settings with stable defaults while preserving all advanced extension keys. */
	async settings(tiferesAlias) {
		return await this.malchusContext.db.get(`/social/aliases/${tiferesAlias}/emailSettings`)
			|| { approved: {}, rules: [], customScript: '', forwarding: { enabled: false, targets: [] } };
	}

	/** Persists the original incoming record before any forwarding, push, or automation work begins. */
	async store(malchusRecipientFolder, tiferesRecord) {
		const yesodPath = `/emails/${malchusRecipientFolder}/threads/${tiferesRecord.correspondent}`;
		await this.malchusContext.db.appendToObj(yesodPath, { key: tiferesRecord.uid, value: tiferesRecord });
	}

	/** Reflects the newly persisted message to the existing Mail websocket surface. */
	notify(tiferesAlias, malchusRecord) {
		this.malchusContext.ws?.sendToAlias?.(tiferesAlias, {
			type: 'NEW_MAIL',
			message: { ...malchusRecord, snippet: `${malchusRecord.textContent.slice(0, 50)}${malchusRecord.textContent.length > 50 ? '...' : ''}` }
		});
	}

	/** Runs forwarding only after the source inbox write has succeeded. */
	async forward(tiferesRecipient, chochmahMessage) {
		return this.yesodForwarding.forwardFromAlias({
			ownerAddress: tiferesRecipient,
			fromAddress: chochmahMessage.senderAddress,
			subject: chochmahMessage.subject,
			content: chochmahMessage.html || chochmahMessage.text,
			text: chochmahMessage.text,
			html: chochmahMessage.html,
			attachments: chochmahMessage.attachments,
			trail: chochmahMessage.forwardingTrail
		});
	}

	/** Runs structured and legacy automation only for safe inbox messages that are neither generated nor self-looping. */
	async automate(chochmahContext) {
		if (chochmahContext.status !== 'inbox' || chochmahContext.autoGenerated) return false;
		const tiferesSelfLoop = IngressMessageSafety.isSelfLoop(
			chochmahContext.message.senderAddress,
			chochmahContext.recipientAddress
		);
		if (tiferesSelfLoop) return false;
		await this.netzachRules.run({
			settings: chochmahContext.settings,
			recipientAlias: chochmahContext.recipientAlias,
			recipientAddress: chochmahContext.recipientAddress,
			senderAddress: chochmahContext.message.senderAddress,
			senderFolder: chochmahContext.message.senderAddress.replace('@', '_at_'),
			subject: chochmahContext.message.subject,
			text: chochmahContext.message.text
		});
		return true;
	}
}

module.exports = { IngressRecipientDelivery };
