import { BotMind } from "./BotMind.js";
import { CollisionSystem } from "./CollisionSystem.js";
import { EnergySystem } from "./EnergySystem.js";
import { GateSystem } from "./GateSystem.js";
import { MovementSystem } from "./MovementSystem.js";
import { PathProbe } from "./PathProbe.js";
import { TrailSystem } from "./TrailSystem.js";

/**
 * SimulationEngine conducts one deterministic pulse while every controller obeys one energy law.
 * The Awtsmoos renews movement, strength, danger, fall, and return in ordered flight;
 * Awtsmoos.com keeps player and bot under the same finite Ohr while one tick joins their light.
 */
export class SimulationEngine {
	constructor(match) {
		this.match = match;
		this.movement = new MovementSystem();
		this.trails = new TrailSystem(match.ledger);
		this.gates = new GateSystem(match.ledger);
		this.collisions = new CollisionSystem();
		this.energy = new EnergySystem();
		this.bots = new BotMind(new PathProbe(match.ledger));
	}

	/** @returns {object[]} Tick-stamped events generated by one authoritative pulse. */
	step(playerIntent = { turn: 0, boost: false }) {
		if (this.match.ended) {
			return [];
		}
		const events = [];
		for (const rider of this.match.riders) {
			if (!rider.alive) {
				this.#advanceRespawn(rider, events);
				continue;
			}
			rider.motion.beginPulse();
			const intent = rider.isBot ? this.bots.intentFor(rider, this.match) : playerIntent;
			const sheltered = this.match.ledger.ownerAt(rider.plane, rider.x, rider.z) === rider.id;
			const energy = this.energy.resolve(rider, Boolean(intent.boost), sheltered);
			this.#recordEnergy(rider, energy, events);
			this.#advanceRider(rider, intent.turn, events);
			if (energy.boosted && rider.alive) {
				this.#advanceRider(rider, 0, events);
			}
		}
		for (const rider of this.collisions.resolveHeads(this.match.riders)) {
			this.#shatter(rider, "head", events);
		}
		this.match.advanceClock();
		if (this.match.ended) {
			this.#event(
				events,
				"round-end",
				{ leaderId: this.match.leaderboard()[0]?.rider.id || null },
				this.match.tick
			);
		}
		return events;
	}

	#advanceRider(rider, turn, events) {
		const movement = this.movement.move(rider, turn);
		if (movement.collision) {
			this.#shatter(rider, movement.collision, events);
			return;
		}
		rider.motion.commit(rider.cell(), rider.heading, turn);
		this.#event(events, "move", { riderId: rider.id, from: movement.previous, to: rider.cell() });
		const trail = this.trails.afterMove(rider, movement.previous);
		if (trail.collision) {
			this.#shatter(rider, "trail", events);
			return;
		}
		if (trail.claimed) {
			this.#event(events, "claim", { riderId: rider.id, cells: trail.claimed });
		}
		const transfer = this.gates.transferIfNeeded(rider, this.match.tick);
		if (transfer) {
			rider.motion.snap(rider.cell(), rider.heading);
			this.#event(events, "gate", transfer);
		}
	}

	#advanceRespawn(rider, events) {
		if (!this.trails.respawnTick(rider)) {
			return;
		}
		if (rider.isBot) {
			this.bots.reset(rider.id);
		}
		this.#event(events, "respawn", { riderId: rider.id, cell: rider.cell() });
	}

	#recordEnergy(rider, result, events) {
		if (result.before !== result.after || result.boosted) {
			this.#event(events, "energy", { riderId: rider.id, ...result });
		}
	}

	#shatter(rider, cause, events) {
		if (!rider.alive) {
			return;
		}
		rider.boosting = false;
		rider.speedState = "cruise";
		this.trails.shatter(rider);
		this.#event(events, "shatter", { riderId: rider.id, cause, cell: rider.cell() });
	}

	#event(events, type, payload, tick = this.match.tick + 1) {
		events.push({ tick, type, ...payload });
	}
}
