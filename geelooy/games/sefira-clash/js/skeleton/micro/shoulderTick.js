export function shoulderTick(p, f, m, body) {
	const s = body.height,
		t = Math.sin((f.motionClock || 0) * 0.23) * (f.attack?.id ? 1 : 0.25);
	p.leftShoulder.y += t * s;
	p.rightShoulder.y -= t * 0.6 * s;
	return p;
}
