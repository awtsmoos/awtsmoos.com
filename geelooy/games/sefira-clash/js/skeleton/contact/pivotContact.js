export function pivotContact(pose, contact, metrics, body) {
	if (!contact.grounded || !(metrics.turnTimer > 0.2)) return pose;
	const s = body.height,
		face = metrics.facing;
	pose.hip.x -= face * 4 * s;
	pose.head.x += face * 8 * s;
	return pose;
}
