export function breathingCycle(f, profile = {}) {
	const rate = profile.breathRate || 0.075,
		t = (f.motionClock || 0) * rate + (profile.idleOffset || 0);
	return { inhale: (Math.sin(t) + 1) / 2, wave: Math.sin(t), rate };
}
