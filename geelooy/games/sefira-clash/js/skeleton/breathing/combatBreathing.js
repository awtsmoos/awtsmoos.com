export function combatBreathing(f, breath) {
	const k = f.attack || f.chargeGlow > 0.1 ? 1 : 0;
	return {
		chest: k * (1.5 + (f.chargeGlow || 0) * 3) * breath.inhale,
		shoulders: k * 2 * breath.wave,
		head: k * 0.8 * breath.wave
	};
}
