/* B"H */

// Step 1: Import the EXACT SAME components the engine uses.
// We are re-creating the engine's consciousness in a controlled environment.
import { createGameState, generateMoves, getMoveFrom, getMoveTo, getMovePiece, getMovePromoted } from '../helpers.js';
import { initializeAll } from '../bitboard-helpers.js';
import * as pgnGen from '../generateFromPgn.js';

// --- DOM Elements ---
const fenInput = document.getElementById('fenInput');
const sanInput = document.getElementById('sanInput');
const runTestButton = document.getElementById('runTestButton');
const output = document.getElementById('output');

// --- Pre-populate with the data from the error ---
fenInput.value = "rnbqkbnr/pppppppp/8/8/3P4/8/PPP1PPPP/RNBQKBNR b KQkq d3 0 1";
sanInput.value = "d5";

// --- The Main Diagnostic Function ---
runTestButton.addEventListener('click', () => {
    // Clear previous results
    output.innerHTML = '';
    const log = (message, className = '') => {
        output.innerHTML += `<span class="${className}">${message}\n</span>`;
    };

    try {
        log('B"H - Initializing the universe from sanctified scriptures...', 'info');
        initializeAll();
        log('Universe is stable. Bitboard tables initialized.', 'success');

        const fen = fenInput.value;
        const targetSan = sanInput.value;
        log(`\n--- TEST SCENARIO ---`);
        log(`FEN: ${fen}`);
        log(`TARGET SAN: "${targetSan}"`);
        log(`-----------------------\n`);

        log('Creating game state from FEN...');
        const state = createGameState(fen);
        log('Game state created. Generating all legal moves...', 'info');

        const legalMoves = generateMoves(state);
        log(`Found ${legalMoves.length} legal moves in this position.`);

        // We need the Scribe (PgnConverter) to translate each move back to SAN
        const scribe = new PgnConverter();
        scribe.setState(state);

        let matchFound = false;
        log('\n--- SCRIBE TRACE: Comparing generated moves to target ---', 'info');
        
        for (const moveInt of legalMoves) {
            // This is the core of the test: we ask the Scribe if THIS moveInt matches the SAN.
            // The isMoveSan function internally generates a SAN and compares it.
            const isMatch = scribe.isMoveSan(moveInt, targetSan, legalMoves);
            
            // For logging, we'll manually generate the SAN to see what the scribe *thinks* the move is.
            const from = getMoveFrom(moveInt);
            const to = getMoveTo(moveInt);
            const piece = getMovePiece(moveInt);
            const pieceChar = 'PNBRQKpnbrqk'[piece];
            const fromSq = String.fromCharCode(97 + (from % 8)) + (8 - Math.floor(from / 8));
            const toSq = String.fromCharCode(97 + (to % 8)) + (8 - Math.floor(to / 8));

            if (isMatch) {
                log(`✅ SUCCESS: Move ${fromSq}${toSq} (${pieceChar}) matches "${targetSan}"!`, 'success');
                matchFound = true;
                break; // We found it, no need to check further.
            } else {
                 // The isMoveSan function already console.logs its reasoning, we just log here.
                 log(`❌ MISMATCH: Move ${fromSq}${toSq} (${pieceChar}) was checked against "${targetSan}". See console for scribe's reasoning.`, 'trace');
            }
        }

        log('\n--- FINAL DIAGNOSIS ---');
        if (matchFound) {
            log('PARADOX RESOLVED: The engine correctly generated and identified the move.', 'success');
        } else {
            log('PARADOX CONFIRMED: The engine generated all legal moves, but none of them could be identified by the Scribe as the target SAN.', 'error');
            log('CONCLUSION: There is a mismatch between the move generator and the SAN generator/parser.', 'error');
            log('NEXT STEP: Examine the console trace logs generated by isMoveSan to see why no generated SAN matched the target.', 'info');
        }

    } catch (e) {
        log(`\n/!\\ A CATASTROPHIC ERROR OCCURRED DURING THE TEST /!\\`, 'error');
        log(e.stack, 'error');
    }
});