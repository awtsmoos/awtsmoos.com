/**
 * @file ProceduralForestSystem.js
 * @description Reveals every canonical tree preset inside one measured Eretz forest.
 */
import {
	generateTreeProceduralData,
	listTreePresets,
	validateTreeProceduralData
} from '../../../../../../../libs/awtsmoos-procedural-core/src/index.js';
import { createForestColliders } from './ForestCollision.js';
import { createMergedForestGeometry } from './ForestGeometry.js';
import { createForestPlacements } from './ForestPlacement.js';
import { createForestPolicy } from './ForestPolicy.js';

const FOREST_POPULATION = 54;
const FOREST_SEED = 613;

function countBy(items, select) {
	const counts = {};
	for (const item of items) {
		const key = select(item);
		counts[key] = (counts[key] || 0) + 1;
	}
	return counts;
}

function buildRecord(placement) {
	const started = performance.now();
	const tree = generateTreeProceduralData(placement.policy.config);
	const validation = validateTreeProceduralData(tree);
	if (!validation.ok) {
		throw new Error(`${placement.policy.name}: ${validation.issues.join(', ')}`);
	}
	return {
		...placement,
		index: placement.policy.index,
		tree,
		scale: placement.policy.targetHeight / validation.height,
		generationMilliseconds: performance.now() - started,
		validation
	};
}

export function createProceduralForest(options) {
	const started = performance.now();
	const names = listTreePresets();
	const policies = Array.from({ length: Math.max(names.length, FOREST_POPULATION) }, (_, index) => (
		createForestPolicy(names[index % names.length], index)
	));
	const placement = createForestPlacements(policies, {
		groundSampler: options.groundSampler,
		roadTriangles: options.roadTriangles,
		obstacleTriangles: options.obstacleTriangles,
		halfSize: options.halfSize,
		seed: FOREST_SEED
	});
	if (placement.placements.length !== policies.length) {
		throw new Error(`Forest placement accepted ${placement.placements.length}/${policies.length} trees.`);
	}
	const records = placement.placements.map(buildRecord);
	const rendered = createMergedForestGeometry(records);
	const collision = createForestColliders(records);
	const presetsUsed = Array.from(new Set(records.map((record) => record.policy.name)));
	const stats = {
		generator: 'awtsmoos-procedural-core/treeGenerator.js',
		seed: FOREST_SEED,
		presetCount: names.length,
		presetsUsed,
		allPresetsPresent: names.every((name) => presetsUsed.includes(name)),
		treeCount: records.length,
		perPreset: countBy(records, (record) => record.policy.name),
		lodTiers: countBy(records, (record) => record.policy.tier),
		placement: {
			...placement.rejections,
			sources: placement.sources,
			minimumSpawnClearance: 32,
			roadClearance: 5.4,
			obstacleClearance: 4.8
		},
		rendering: rendered.stats,
		collision: collision.stats,
		generationMilliseconds: Number((performance.now() - started).toFixed(2)),
		deterministic: true,
		mobilePolicy: 'preset-clone-recursion-and-radial-caps',
		unsupported: {
			wind: 'tiny renderer only exposes grass-specific deformation',
			fruit: 'not generated by canonical tree engine',
			flowers: 'not generated by canonical tree engine',
			roots: 'no dedicated root geometry path',
			dynamicLod: 'static placement-tier LOD is used to preserve two draw calls'
		}
	};
	rendered.group.userData.AwtsmoosForest = stats;
	return {
		group: rendered.group,
		colliders: collision.colliders,
		records,
		stats
	};
}

export default createProceduralForest;
