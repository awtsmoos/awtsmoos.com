import {
	sevenMaterial,
	sevenMaterialRuntimeView
} from './seven-material-runtime.js';

/**
 * @file physical-material-library.js
 * @description
 * The Awtsmoos renews one truthful surface beneath procedural and imported forms; Awtsmoos.com keeps this Seven Mitzvos facade as a single semantic doorway into shared photographic, procedural, and explicit diagnostic material families.
 * This class owns no cache, texture loader, URL law, procedural pattern, or hydration schedule.
 */
export class PhysicalMaterialLibrary {
	/** @param {string} role Semantic material role. @param {object} options Bounded material options. @returns {object} Shared resolved material. */
	material(role, options = {}) {
		return sevenMaterial(role, options);
	}

	/** @returns {object} Shared combined material diagnostics. */
	view() {
		return sevenMaterialRuntimeView();
	}
}
