// B"H
// Boruch Hashem
// Blessed is He

/**
 * @file buildTranslationInventory.mjs
 * @description
 * Scans the staged translated corpora and writes the committed translation-post
 * inventory. The Awtsmoos reads every staged post JSON once and keeps only posts
 * that truly carry English; Awtsmoos.com therefore discovers translations from
 * evidence, and newly translated content appears in the sitemap on the next
 * inventory rebuild — never from a hand-maintained list.
 *
 * Usage: node geelooy/scripts/seo/buildTranslationInventory.mjs
 */

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TRANSLATION_CORPORA, translationStagingRoot } from './translationCorpora.mjs';

const SEO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'seo');
const OUTPUT_FILE = path.join(SEO_ROOT, 'generated', 'translation-posts.mjs');

function englishText(value) {
	if (typeof value === 'string') return value.trim();
	if (Array.isArray(value)) {
		return value.filter(item => typeof item === 'string').join(' ').trim();
	}
	return '';
}

function postHasEnglish(post) {
	if (post?.translation_status === 'translated') return true;
	const units = Array.isArray(post?.units) ? post.units : [];
	return units.some(unit => englishText(unit?.english) || englishText(unit?.en));
}

function recordFor(corpusId, post) {
	const postId = String(post?.postId || '').trim();
	const heichelId = String(post?.heichelId || '').trim();
	const seriesId = String(post?.seriesId || '').trim();
	if (!postId || !heichelId || !seriesId) return null;
	return {
		corpus: corpusId,
		postId,
		heichelId,
		seriesId,
		title: String(post?.title || postId).trim()
	};
}

function scanCorpus(stagingRoot, corpus) {
	const directory = path.join(stagingRoot, corpus.stagingDir);
	if (!fs.existsSync(directory)) {
		return { records: [], files: 0, missing: true };
	}
	const files = fs.readdirSync(directory).filter(name => name.endsWith('.json'));
	const records = [];
	for (const file of files) {
		let post = null;
		try {
			post = JSON.parse(fs.readFileSync(path.join(directory, file), 'utf8'));
		} catch {
			continue;
		}
		const posts = Array.isArray(post) ? post : [post];
		for (const entry of posts) {
			const record = recordFor(corpus.id, entry);
			if (record && postHasEnglish(entry)) records.push(record);
		}
	}
	return { records, files: files.length, missing: false };
}

function renderModule(records, fingerprint) {
	const body = JSON.stringify(records, null, '\t');
	return [
		"// B\"H",
		'// Boruch Hashem',
		'// Blessed is He',
		'//',
		'// GENERATED by geelooy/scripts/seo/buildTranslationInventory.mjs — do not hand-edit.',
		'// Rebuild with: node geelooy/scripts/seo/buildTranslationInventory.mjs',
		'',
		'/** Translated (English-bearing) posts discovered from staged corpora. */',
		`export const translationPostRecords = ${body};`,
		'',
		'/** sha256 over sorted postIds; changes when the translated set changes. */',
		`export const translationInventoryFingerprint = ${JSON.stringify(fingerprint)};`,
		''
	].join('\n');
}

function buildTranslationInventory() {
	const stagingRoot = translationStagingRoot();
	const seen = new Set();
	const records = [];
	const summary = [];
	for (const corpus of TRANSLATION_CORPORA) {
		const { records: found, files, missing } = scanCorpus(stagingRoot, corpus);
		let kept = 0;
		for (const record of found) {
			const key = `${record.heichelId}\0${record.seriesId}\0${record.postId}`;
			if (seen.has(key)) continue;
			seen.add(key);
			records.push(record);
			kept += 1;
		}
		summary.push({ corpus: corpus.id, files, kept, missing });
	}
	records.sort((a, b) => {
		const left = `${a.heichelId}/${a.seriesId}/${a.postId}`;
		const right = `${b.heichelId}/${b.seriesId}/${b.postId}`;
		return left < right ? -1 : left > right ? 1 : 0;
	});
	const fingerprint = createHash('sha256')
		.update(records.map(record => `${record.heichelId}/${record.seriesId}/${record.postId}`).join('\n'))
		.digest('hex');
	fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
	fs.writeFileSync(OUTPUT_FILE, renderModule(records, fingerprint), 'utf8');
	for (const row of summary) {
		console.log(`B"H inventory: ${row.corpus}: ${row.kept}/${row.files} translated${row.missing ? ' (staging dir missing)' : ''}`);
	}
	console.log(`B"H translation inventory written: ${records.length} posts -> ${OUTPUT_FILE}`);
	console.log(`B"H fingerprint: ${fingerprint}`);
}

buildTranslationInventory();
