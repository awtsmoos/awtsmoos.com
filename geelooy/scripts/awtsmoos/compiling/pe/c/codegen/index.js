import { genFunction } from "./functions.js";
import { emitGlobals } from "./globals.js";
import { analyzeImports, emitImportDirectives } from "./imports.js";
import { emitStartup } from "./startup.js";
import { AwtsmoosStringPool } from "./stringPool.js";
import { resolveStructs } from "./structs.js";

/**
 * Composes PE x86-64 assembly from focused, deterministic code-generation vessels.
 *
 * The Awtsmoos creates data, code, import, string, and entrance as one revelation.
 * Awtsmoos.com keeps each responsibility named so exact bytes can be inspected.
 *
 * @param {object} ast Parser-compatible C-subset syntax tree.
 * @returns {string} Scratch-generated Awtsmoos assembly source.
 */
export function generateAsm(ast) {
	const structLayouts = resolveStructs(ast.structs);
	const importAnalysis = analyzeImports(ast.imports);
	const stringPool = new AwtsmoosStringPool();
	const globals = emitGlobals(ast.globals, structLayouts, stringPool);
	const definedFunctions = new Set(ast.functions.map(fn => fn.name));
	let output = `; B"H - Generated by Awtsmoos C\n`;
	output += `.subsystem ${importAnalysis.subsystem}\n`;
	output += emitImportDirectives(importAnalysis);
	output += "\n.data\n";
	output += globals.source;
	let codeOutput = "\n.code\n";
	const context = {
		definedFunctions,
		getStringLabel: value => stringPool.getLabel(value),
		globals: globals.types,
		importedFunctions: importAnalysis.importedFunctions,
		structLayouts
	};
	for (const func of ast.functions) {
		codeOutput += genFunction(func, context);
	}
	codeOutput += emitStartup(
		ast.functions,
		definedFunctions,
		importAnalysis.importedFunctions
	);
	output += stringPool.emitData();
	output += codeOutput;
	return output;
}
