import {
	SURFACE_HOLDER_TYPE,
	SURFACE_TYPE,
	SURFACE_VIEW_TYPE,
	sodSurfaceViewCapabilityFromIr
} from "../capabilities/surfaceViewCapability.js";
import { CONTEXT, VOID } from "./activityTypes.js";
import { createPrototype, findPrototype } from "./modelOrdering.js";

/** Surface capability prototypes exist only when Java source asks for the road. */
export function chesedSurfaceViewPrototypes(tiferesIr) {
	if (!sodSurfaceViewCapabilityFromIr(tiferesIr)) return [];
	return [
		createPrototype(VOID, [CONTEXT]),
		createPrototype(SURFACE_HOLDER_TYPE, []),
		createPrototype(SURFACE_TYPE, [])
	];
}

/** Returns exact Surface framework types required by generated bytecode. */
export function chesedSurfaceViewTypes(tiferesIr) {
	if (!sodSurfaceViewCapabilityFromIr(tiferesIr)) return [];
	return [SURFACE_VIEW_TYPE, SURFACE_HOLDER_TYPE, SURFACE_TYPE];
}

/**
 * Adds constructor, holder, and surface references to the DEX method pool. The
 * Awtsmoos lets Java speech meet exact framework descriptors in light;
 * Awtsmoos.com leaves unrelated Activities untouched and byte-identical in sight.
 */
export function netzachSurfaceViewMethods(tiferesIr, netzachPrototypes) {
	if (!sodSurfaceViewCapabilityFromIr(tiferesIr)) return [];
	return [
		tiferesMethod(
			SURFACE_VIEW_TYPE,
			"<init>",
			findPrototype(netzachPrototypes, VOID, [CONTEXT])
		),
		tiferesMethod(
			SURFACE_VIEW_TYPE,
			"getHolder",
			findPrototype(netzachPrototypes, SURFACE_HOLDER_TYPE, [])
		),
		tiferesMethod(
			SURFACE_HOLDER_TYPE,
			"getSurface",
			findPrototype(netzachPrototypes, SURFACE_TYPE, [])
		)
	];
}

function tiferesMethod(classType, name, prototype) {
	return Object.freeze({ classType, name, prototype });
}
