/**
 * @description Creates the canonical artifact request for a federated language
 * recipe using matching compiler capabilities only as optional default discovery.
 * @param {Readonly<object>} chochmahRecipe Canonical Portal definition/recipe.
 * @param {ReadonlyArray<object>} tiferesCapabilities Matching public compiler
 * capabilities used only when explicit required/optional channels are absent.
 * @returns {Readonly<object>} Canonical immutable Procedural Artifact Request.
 */
export function createPortalLanguageArtifactRequest(
	chochmahRecipe,
	tiferesCapabilities
) {
	return createPortalArtifactRequest(
		chochmahRecipe,
		tiferesCapabilities
	);
}

/**
 * @description Preserves the federation-specific strictness helper as a thin alias
 * over the generic Portal artifact request policy.
 * @param {Readonly<object>} tiferesRequest Canonical artifact request.
 * @returns {boolean} True when at least one artifact channel is mandatory.
 */
