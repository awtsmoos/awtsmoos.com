function buildManifest(cfg) {
	const manifest = {
		manifest_version: 3,
		name: cfg.name,
		version: VERSION,
		description: cfg.description,
		action: {
			default_popup: "popup.html",
			default_title: "Shliach Browser Link (" + cfg.id + ")",
			default_icon: { 16: "icons/icon16.png", 48: "icons/icon48.png", 128: "icons/icon128.png" },
		},
		background: { service_worker: "background.js" },
		icons: { 16: "icons/icon16.png", 48: "icons/icon48.png", 128: "icons/icon128.png" },
		permissions: cfg.permissions,
		host_permissions: cfg.hostPermissions,
	};
	if (cfg.contentScripts.length > 0) manifest.content_scripts = cfg.contentScripts;
	return manifest;
}

function buildVersionJs(cfg) {
	return (
		"// Generated by build.mjs — do not edit by hand. Edit the version\n" +
		"// config in build.mjs and rebuild.\n" +
		"globalThis.SHLIACH_VERSION = " +
		JSON.stringify({ id: cfg.id, name: cfg.name, version: VERSION, features: cfg.features }, null, 2) +
		";\n"
	);
}

function copyDir(from, to) {
	fs.mkdirSync(to, { recursive: true });
	for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
		const src = path.join(from, entry.name);
		const dst = path.join(to, entry.name);
		if (entry.isDirectory()) copyDir(src, dst);
		else fs.copyFileSync(src, dst);
	}
}

function sha256(file) {
	return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function main() {
	const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "shliach-ext-"));
	const sums = [];
	try {
		fs.mkdirSync(OUT, { recursive: true });
		for (const cfg of Object.values(VERSIONS)) {
			const dir = path.join(tmpRoot, cfg.id);
			copyDir(SRC, dir);
			if (!cfg.includeOffscreen) {
				fs.rmSync(path.join(dir, "offscreen.html"), { force: true });
				fs.rmSync(path.join(dir, "offscreen.js"), { force: true });
			}
			// The content script cannot importScripts, so the DOM readers
			// (extract.js) are concatenated in front of it — one source,
			// shared by the debugger path (background.js) and the content
			// script path, with no copy-paste drift.
			const extractSrc = fs.readFileSync(path.join(SRC, "extract.js"), "utf8");
			const contentSrc = fs.readFileSync(path.join(dir, "content.js"), "utf8");
			fs.writeFileSync(path.join(dir, "content.js"), extractSrc + "\n" + contentSrc, "utf8");
			fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(buildManifest(cfg), null, 2) + "\n", "utf8");
			fs.writeFileSync(path.join(dir, "version.js"), buildVersionJs(cfg), "utf8");
			const zipName = `awtsmoos-shliach-browser-${cfg.id}-${VERSION}.zip`;
			const zipPath = path.join(OUT, zipName);
			if (fs.existsSync(zipPath)) fs.rmSync(zipPath);
			execFileSync("zip", ["-qr", zipPath, "."], { cwd: dir, stdio: "pipe" });
			const sum = sha256(zipPath);
			sums.push(`${sum}  ${zipName}`);
			console.log(`built ${zipName} (${fs.statSync(zipPath).size} bytes, sha256 ${sum.slice(0, 12)}…)`);
		}
		fs.writeFileSync(path.join(OUT, "SHA256SUMS.txt"), sums.join("\n") + "\n", "utf8");
		console.log("wrote downloads/SHA256SUMS.txt");
	} finally {
		fs.rmSync(tmpRoot, { recursive: true, force: true });
	}
}

main();
