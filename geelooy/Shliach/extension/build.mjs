// Build the Shliach Browser Link extension in three permission versions
// from ONE shared codebase, and zip each version for download.
//
//   node build.mjs
//
// Output (all paths relative to this file):
//   downloads/awtsmoos-shliach-browser-minimal-1.0.0.zip
//   downloads/awtsmoos-shliach-browser-standard-1.0.0.zip
//   downloads/awtsmoos-shliach-browser-unrestricted-1.0.0.zip
//   downloads/SHA256SUMS.txt
//
// The build assembles each version in a temp dir (never committed), then
// zips it. The per-version differences are ONLY the manifest (permissions,
// host permissions, content scripts) and version.js (feature flags). Every
// other file is the same shared source. That is the whole point: one
// codebase, three permission levels, no copy-paste drift.

