function tick() {
	return new Promise((resolve) => setImmediate(resolve));
}

function serverResponse(envelope, type, payload) {
	return JSON.stringify({
		protocol: "awtsmoos.realtime",
		application: "shliach-browser",
		version: 1,
		type,
		requestId: envelope.requestId,
		sequence: envelope.sequence,
		payload,
	});
}

test("relay: connectRelay opens one socket and joins with the code", async () => {
	const { sandbox, sockets } = loadBackground(UNRESTRICTED);
	const promise = sandbox.connectRelay("abcdef");
	assert.equal(sockets.length, 1);
	const socket = sockets[0];
	assert.equal(socket.url, "wss://awtsmoos.com/api/shliach/relay");
	socket.readyState = 1;
	socket.onopen();
	await tick();
	await tick();
	assert.equal(socket.sent.length, 1, "the worker should send exactly one join envelope");
	const envelope = JSON.parse(socket.sent[0]);
	assert.equal(envelope.protocol, "awtsmoos.realtime");
	assert.equal(envelope.application, "shliach-browser");
	assert.equal(envelope.version, 1);
	assert.equal(envelope.type, "shliach.join");
	assert.equal(envelope.payload.code, "ABCDEF", "the code is uppercased before sending");
	assert.equal(envelope.payload.role, "browser");
	assert.equal(envelope.payload.version, "unrestricted");
	assert.match(envelope.requestId, /^req-\d+-[a-z0-9]+$/);
	assert.equal(envelope.sequence, 1);
	// The server's own validator accepts this envelope.
	const parsed = parseIncomingMessage(socket.sent[0]);
	assert.equal(parsed.kind, "versioned");
	assert.equal(parsed.envelope.type, "shliach.join");
	assert.equal(parsed.envelope.application, "shliach-browser");
	// The server answers; the connect promise resolves paired.
	socket.onmessage({ data: serverResponse(envelope, "shliach.joined", { code: "ABCDEF", paired: true }) });
	const result = await promise;
	// Field-by-field: the object was built inside the vm context, so its
	// prototype differs from this realm's Object.prototype and a strict
	// deepEqual would fail on prototype, not on content.
	assert.equal(result.ok, true);
	assert.equal(result.state, "paired");
	sandbox.disconnectRelay();
});

test("relay: an agent ping command runs and its result is sent back", async () => {
	const { sandbox, sockets } = loadBackground(UNRESTRICTED);
	const promise = sandbox.connectRelay("ABCDEF");
	const socket = sockets[0];
	socket.readyState = 1;
	socket.onopen();
	await tick();
	await tick();
	const join = JSON.parse(socket.sent[0]);
	socket.onmessage({ data: serverResponse(join, "shliach.joined", { code: "ABCDEF", paired: true }) });
	await promise;
	// The agent sends a ping as an event (no requestId — events are
	// distinguished from responses by its absence).
	socket.onmessage({
		data: JSON.stringify({
			protocol: "awtsmoos.realtime",
			application: "shliach-browser",
			version: 1,
			type: "shliach.message",
			payload: { from: "agent", data: { command: "ping", id: "ping-1" } },
		}),
	});
	await tick();
	await tick();
	assert.equal(socket.sent.length, 2, "the worker should answer with one shliach.send");
	const answer = JSON.parse(socket.sent[1]);
	assert.equal(answer.type, "shliach.send");
	assert.equal(answer.payload.data.ok, true);
	assert.equal(answer.payload.data.command, "ping");
	assert.equal(answer.payload.data.id, "ping-1");
	assert.equal(answer.payload.data.result.version, "unrestricted");
	assert.equal(answer.payload.data.result.relay, "paired");
	// The answer envelope also passes the server's validator.
	const parsed = parseIncomingMessage(socket.sent[1]);
	assert.equal(parsed.kind, "versioned");
	assert.equal(parsed.envelope.type, "shliach.send");
	// The server acknowledges the send, clearing the pending request.
	socket.onmessage({ data: serverResponse(answer, "shliach.sent", { delivered: true }) });
	await tick();
	sandbox.disconnectRelay();
});

test("relay: a peer-left event drops the state back to connected", async () => {
	const { sandbox, sockets, sentRuntimeMessages } = loadBackground(UNRESTRICTED);
	const promise = sandbox.connectRelay("ABCDEF");
	const socket = sockets[0];
	socket.readyState = 1;
	socket.onopen();
	await tick();
	await tick();
	const join = JSON.parse(socket.sent[0]);
	socket.onmessage({ data: serverResponse(join, "shliach.joined", { code: "ABCDEF", paired: true }) });
	await promise;
	socket.onmessage({
		data: JSON.stringify({
			protocol: "awtsmoos.realtime",
			application: "shliach-browser",
			version: 1,
			type: "shliach.peer-left",
			payload: { role: "agent" },
		}),
	});
	await tick();
	const last = sentRuntimeMessages[sentRuntimeMessages.length - 1];
	assert.equal(last.action, "relayState");
	assert.equal(last.state, "connected");
	sandbox.disconnectRelay();
});

