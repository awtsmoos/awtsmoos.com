async function pair(load) {
	const promise = load.sandbox.connectRelay("ABCDEF");
	const socket = load.sockets[0];
	socket.readyState = 1;
	socket.onopen();
	await tick();
	await tick();
	const join = JSON.parse(socket.sent[0]);
	socket.onmessage({ data: serverResponse(join, "shliach.joined", { code: "ABCDEF", paired: true }) });
	await promise;
	return socket;
}

function sendAgentCommand(socket, data) {
	socket.onmessage({
		data: JSON.stringify({
			protocol: "awtsmoos.realtime",
			application: "shliach-browser",
			version: 1,
			type: "shliach.message",
			payload: { from: "agent", data },
		}),
	});
}

async function lastAnswer(socket) {
	await tick();
	await tick();
	const answer = JSON.parse(socket.sent[socket.sent.length - 1]);
	assert.equal(answer.type, "shliach.send");
	return answer;
}

test("relay: page.summary runs through the debugger and returns the result", async () => {
	const load = loadBackground(UNRESTRICTED);
	const socket = await pair(load);
	sendAgentCommand(socket, { command: "page.summary", id: "sum-1" });
	const answer = await lastAnswer(socket);
	assert.equal(answer.payload.data.ok, true);
	assert.equal(answer.payload.data.command, "page.summary");
	assert.equal(answer.payload.data.id, "sum-1");
	assert.equal(answer.payload.data.result.evaluated, true);
	// The worker sent the reader's own source into the page via
	// Runtime.evaluate — the expression carries the function, not a call
	// to something the page defines.
	const evaluate = load.debuggerCalls.find((c) => c.method === "Runtime.evaluate");
	assert.ok(evaluate, "page.summary should use Runtime.evaluate");
	assert.match(evaluate.params.expression, /function extractPageSummary/);
	assert.match(evaluate.params.expression, /return extractPageSummary\(/);
	assert.equal(evaluate.params.returnByValue, true);
	socket.onmessage({ data: serverResponse(answer, "shliach.sent", { delivered: true }) });
	await tick();
	load.sandbox.disconnectRelay();
});

test("relay: page.html, page.dom and page.elements each serialize their reader into the page", async () => {
	const load = loadBackground(UNRESTRICTED);
	const socket = await pair(load);
	for (const [command, fn] of [
		["page.html", "extractPageHtml"],
		["page.dom", "extractPageDom"],
		["page.elements", "extractPageElements"],
	]) {
		const before = load.debuggerCalls.filter((c) => c.method === "Runtime.evaluate").length;
		sendAgentCommand(socket, { command, id: `${command}-1` });
		const answer = await lastAnswer(socket);
		assert.equal(answer.payload.data.ok, true, `${command} should succeed`);
		assert.equal(answer.payload.data.command, command);
		const calls = load.debuggerCalls.filter((c) => c.method === "Runtime.evaluate");
		assert.equal(calls.length, before + 1, `${command} should evaluate exactly once`);
		assert.match(calls[calls.length - 1].params.expression, new RegExp(`function ${fn}`));
		assert.match(calls[calls.length - 1].params.expression, new RegExp(`return ${fn}\\(`));
		socket.onmessage({ data: serverResponse(answer, "shliach.sent", { delivered: true }) });
		await tick();
	}
	load.sandbox.disconnectRelay();
});

test("relay: a result over the 64 KiB limit is answered with a retry hint, not sent", async () => {
	const load = loadBackground(UNRESTRICTED);
	load.setHugeHtml(true);
	const socket = await pair(load);
	sendAgentCommand(socket, { command: "page.html", id: "html-big" });
	const answer = await lastAnswer(socket);
	assert.equal(answer.payload.data.ok, false);
	assert.match(answer.payload.data.error, /over the relay's 64 KiB limit/);
	assert.match(answer.payload.data.error, /retry page\.html with a smaller length/);
	assert.ok(answer.payload.data.bytes > 56 * 1024);
	// The oversized answer was never put on the wire as data — only the
	// small error reply was sent, so the relay never rejects it.
	assert.ok(JSON.stringify(answer).length < 64 * 1024);
	load.sandbox.disconnectRelay();
});
