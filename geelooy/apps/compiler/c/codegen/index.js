import { genFunction } from './functions.js';
import { resolveStructs } from './structs.js';

export function generateAsm(ast) {
    // 1. Resolve Struct Layouts
    const structLayouts = resolveStructs(ast.structs);

    // 2. Imports & Subsystem Detection
    const dlls = {};
    const importedFunctions = new Set();
    let isGui = false;
    
    for (const imp of ast.imports) {
        if (!dlls[imp.dll]) dlls[imp.dll] = new Set();
        dlls[imp.dll].add(imp.func);
        importedFunctions.add(imp.func);
        
        // Auto-detect GUI
        if (['MessageBoxA', 'CreateWindowExA', 'RegisterClassA'].includes(imp.func)) {
            isGui = true;
        }
    }
    
    let output = `; B"H - Generated by Awtsmoos C\n.subsystem ${isGui ? 'gui' : 'console'}\n`;

    for (const dll in dlls) {
        output += `.import ${dll} ${Array.from(dlls[dll]).join(' ')}\n`;
    }

    // 3. Data & Globals
    const stringLiterals = new Map();
    let strCount = 0;
    function getStringLabel(str) {
        if (stringLiterals.has(str)) return stringLiterals.get(str);
        const lbl = `str_${strCount++}`;
        stringLiterals.set(str, lbl);
        return lbl;
    }
    
    // Helper to escape strings for ASM source
    function escapeString(str) {
        return str
            .replace(/\\/g, '\\\\')
            .replace(/"/g, '\\"')
            .replace(/\n/g, '\\n')
            .replace(/\r/g, '\\r')
            .replace(/\t/g, '\\t')
            .replace(/\0/g, '\\0');
    }

    function toLittleEndianBytes(valStr) {
        try {
            // Handle hex or decimal
            let val = BigInt(valStr); 
            const buf = new Uint8Array(8);
            const view = new DataView(buf.buffer);
            view.setBigInt64(0, val, true);
            return buf.join(', ');
        } catch(e) {
            return "0, 0, 0, 0, 0, 0, 0, 0";
        }
    }

    output += `\n.data\n`;
    
    // Globals Map for Type Inference
    const globals = new Map();

    // Globals Emission
    for (const g of ast.globals) {
        globals.set(g.name, g.type); // Store type for codegen context

        // Note: We rely on linker.js to align the start of each new data blob (global) to 8 bytes.
        // We do NOT emit explicit padding here.

        if (g.type.ptr > 0 && typeof g.value === 'string' && g.value.startsWith('"')) {
            const val = g.value.slice(1, -1);
            const lbl = getStringLabel(val);
            output += `${g.name}: ${lbl}\n`;
        } else if (g.value !== null) {
            if (/^-?\d+$/.test(g.value) || /^-?0x[0-9a-fA-F]+$/.test(g.value)) {
                // Emit 8 bytes for integers to ensure 64-bit access is valid
                const bytes = toLittleEndianBytes(g.value);
                output += `${g.name}: ${bytes}\n`;
            } else {
                output += `${g.name}: ${g.value}\n`; // Label ref
            }
        } else {
             let size = 8;
             if (g.type.base !== 'int' && g.type.base !== 'char' && g.type.ptr === 0) {
                 const sl = structLayouts.get(g.type.base);
                 if (sl) size = sl.size;
             }
             const zeros = new Array(size).fill(0).join(', ');
             output += `${g.name}: ${zeros}\n`;
        }
    }

    let codeOutput = `\n.code\n`;
    const definedFunctions = new Set(ast.functions.map(f => f.name));
    
    const ctx = {
        structLayouts,
        definedFunctions,
        importedFunctions,
        getStringLabel,
        globals // Pass globals to context
    };

    for (const func of ast.functions) {
        codeOutput += genFunction(func, ctx);
    }
    
    if (ast.functions.find(f => f.name === 'main')) {
         codeOutput += `
start:
AND RSP, 0xFFFFFFFFFFFFFFF0
SUB RSP, 32
CALL main
XOR RCX, RCX
`;
         if (definedFunctions.has('exit') || importedFunctions.has('exit')) {
             codeOutput += `CALL exit\n`;
         } else if (importedFunctions.has('ExitProcess')) {
             codeOutput += `CALL ExitProcess\n`;
         } else {
             codeOutput += `CALL ExitProcess\n`;
         }
    }

    // Emit String Literals
    for (const [str, lbl] of stringLiterals) {
        output += `${lbl}: "${escapeString(str)}"\n`;
        // Note: asm/parser.js automatically appends a null byte to strings.
        // No need to emit 'db 0' here.
    }

    output += codeOutput;
    return output;
}