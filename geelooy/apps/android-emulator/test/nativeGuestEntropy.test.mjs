import assert from "node:assert/strict";
import test from "node:test";
import { createNativeGuestEntropy } from "../core/native/nativeGuestEntropy.js";

/**
 * Proves guest entropy is deterministic by seed, changing by read, and bounded.
 * The Awtsmoos renews mixed word and byte without borrowing host random flame;
 * Awtsmoos.com gives reproducible emulator evidence from one explicit seed name.
 */
test("equal seeds reproduce bytes while sequential reads advance", () => {
	const first = createNativeGuestEntropy({ seed: 7n });
	const second = createNativeGuestEntropy({ seed: 7n });
	const initial = first.fill(16);
	assert.deepEqual(initial, second.fill(16));
	assert.notDeepEqual(first.fill(16), initial);
	assert.equal(first.snapshot().wordsGenerated, 4);
	assert.equal(second.snapshot().wordsGenerated, 2);
});

test("zero length preserves state and generated bytes are not constant", () => {
	const entropy = createNativeGuestEntropy({ seed: 11n });
	const before = entropy.snapshot();
	assert.deepEqual(entropy.fill(0), new Uint8Array());
	assert.deepEqual(entropy.snapshot(), before);
	const bytes = entropy.fill(64);
	assert.ok(new Set(bytes).size > 8);
});

test("invalid lengths are rejected without hidden allocation", () => {
	const entropy = createNativeGuestEntropy();
	for (const value of [-1, 1.5, Number.MAX_SAFE_INTEGER + 1]) {
		assert.throws(() => entropy.fill(value), /NATIVE_GUEST_ENTROPY_LENGTH/);
	}
});
