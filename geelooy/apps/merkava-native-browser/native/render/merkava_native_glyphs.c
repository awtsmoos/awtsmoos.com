static const uint8_t SPACE[7] = { 0, 0, 0, 0, 0, 0, 0 };
static const uint8_t FALLBACK[7] = { 0x1f, 0x11, 0x15, 0x15, 0x11, 0x11, 0x1f };

/** Returns seven 5-bit rows for one ASCII glyph in the built-in fallback font. */
const uint8_t* awts_native_ascii_glyph(uint8_t character) {
	if (character >= 'a' && character <= 'z') {
		character = (uint8_t)(character - 'a' + 'A');
	}
	if (character >= 'A' && character <= 'Z') {
		return LETTERS[character - 'A'];
	}
	if (character >= '0' && character <= '9') {
		return DIGITS[character - '0'];
	}
	if (character == ' ') {
		return SPACE;
	}
	return FALLBACK;
}
