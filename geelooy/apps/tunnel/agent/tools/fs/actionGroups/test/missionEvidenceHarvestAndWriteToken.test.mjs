// B"H
import { createRequire } from 'module';
import fs from 'fs/promises';
import os from 'os';
import path from 'path';
import assert from 'assert/strict';
const require = createRequire(import.meta.url);
const Lock = require('../../mission/lock/index.js');
const Harvester = require('../../mission/evidenceHarvester/index.js');
const Quota = require('../../mission/evidenceQuota/index.js');
const Firewall = require('../../mission/firewall/index.js');
const Court = require('../../mission/releaseCourt/index.js');
const { buildActions } = require('../../actions.js');
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'mission-harvest-token-'));
await fs.writeFile(path.join(root, 'README.md'), 'missionBootResume missionNext8Plan releaseCourt', 'utf8');
await fs.writeFile(path.join(root, 'package.json'), '{"scripts":{"test":"echo ok"}}', 'utf8');
await fs.mkdir(path.join(root, 'geelooy/apps/tunnel/agent'), { recursive:true });
await fs.writeFile(path.join(root, 'geelooy/apps/tunnel/agent/manifest.txt'), 'releaseCourt', 'utf8');
const config = { root, repoRoot: process.cwd(), tools:{ fsRead:true, fsWrite:true }, allowWrite:true };
let lock = Lock.start(config, { action:'missionStart', missionId:'m1', mustCallNext:{ action:'missionNext', missionId:'m1' } }, { autoSeedNext8:false, minimumRuntimeMs:0 });
lock.evidenceQuotas = { inspection:2, verification:0, review:0, repeatBetter:0 }; lock.minimumUntil = new Date(Date.now()-1000).toISOString(); lock.next8Completed = true; lock.repeatBetterDone = true; lock.verificationSeen = true; Lock.set(config, lock);
const harvest = await Harvester.run(config, lock, {}, buildActions);
assert.equal(harvest.harvested, true);
assert(Quota.issues(config, lock).issues.length === 0);
const denied = Firewall.check(config, 'write', lock, { action:'write', path:'a.js', writeTokenTtlMs:1 });
assert.equal(denied.ok, false);
await new Promise(r => setTimeout(r, 5));
assert.equal(Firewall.check(config, 'write', lock, { action:'write', path:'a.js', missionWriteToken:denied.missionWriteToken }).ok, false);
const fresh = Firewall.check(config, 'write', lock, { action:'write', path:'b.js' });
assert.equal(Firewall.check(config, 'write', lock, { action:'write', path:'other.js', missionWriteToken:fresh.missionWriteToken }).ok, false);
assert.equal(Firewall.check(config, 'write', lock, { action:'write', path:'b.js', missionWriteToken:fresh.missionWriteToken }).ok, true);
const blocked = Court.guard(config, lock, { ok:true, action:'missionFinalize', finalAnswerAllowed:true }, {});
assert(blocked.releaseExplanation);
console.log(JSON.stringify({ ok:true, harvested:harvest.evidence.length, explanation:blocked.releaseExplanation.slice(0,32) }, null, 2));
