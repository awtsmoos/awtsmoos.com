/**
 * @file StudioMitzvahWorldAssetProvider.js
 * The Awtsmoos renews the authored Chossid while no mesh becomes the source of life;
 * Awtsmoos.com keeps MitzvahWorld's GLB, materials, and animation clips intact beyond the lightweight preview strife.
 *
 * The Chossid URL is resolved the way the game itself publishes it: every
 * Mitzvah World build regenerates build/generated/mitzvah-world-essential-assets.json
 * with assets.canonicalChossid.publicUrl pointing at the content-addressed
 * (sha256-folder) GLB of that exact build. This provider reads that manifest
 * at runtime, so a future game build can move the asset without breaking the
 * studio. The previous constant froze one build's hash inside a retired
 * directory layout (/games/mitzvahWorld/assets/models/player/<sha>/), a path
 * that exists in no deployed tree, so every character load answered 404.
 * When the manifest cannot be read, resolution falls back to the build's
 * stable canonical copy (build/generated/assets/canonical-chossid.glb, the
 * same 2,027,368 authored bytes, pinned by the game's own
 * ProductionBuildContentTests).
 */

const CHOSSID_MANIFEST_URL = '/games/mitzvahWorld/build/generated/mitzvah-world-essential-assets.json';
const CHOSSID_FALLBACK_URL = '/games/mitzvahWorld/build/generated/assets/canonical-chossid.glb';

let chossidUrlPromise = null;

/** Describe authored MitzvahWorld assets without loading their heavy runtime. */
export function describeMitzvahWorldAssets() {
	return {
		provider: 'mitzvah-world-assets',
		lazy: true,
		assets: [
			{
				id: 'chossid',
				label: 'Chossid',
				url: CHOSSID_FALLBACK_URL,
				resolution: 'essential-assets-manifest',
				manifestUrl: CHOSSID_MANIFEST_URL,
				format: 'glb',
				loader: 'ChaiChossidLoader',
				preservesAuthoredMaterials: true,
				preservesAuthoredAnimations: true,
				castsShadows: true,
				receivesShadows: true
			}
		]
	};
}

/**
 * Resolve the canonical public URL for the authored Chossid model from the
 * game's own published essential-assets manifest (regenerated by every
 * Mitzvah World build, so the answer can never rot against a frozen hash).
 * Any manifest failure resolves to the build's stable canonical copy instead
 * of failing the character load. The promise is cached per page session;
 * pass a fetch implementation only in tests.
 */
export function resolveMitzvahWorldChossidUrl(fetchFunction) {
	if (typeof fetchFunction === 'function') {
		return fetchChossidUrl(fetchFunction);
	}
	if (!chossidUrlPromise) {
		chossidUrlPromise = fetchChossidUrl(globalThis.fetch);
	}
	return chossidUrlPromise;
}

/** Return the build's stable canonical-copy URL (synchronous descriptor use). */
export function mitzvahWorldChossidUrl() {
	return CHOSSID_FALLBACK_URL;
}

/** Reads the essential-assets manifest once and extracts the Chossid public URL. */
async function fetchChossidUrl(fetchFunction) {
	try {
		if (typeof fetchFunction !== 'function') return CHOSSID_FALLBACK_URL;
		const response = await fetchFunction(CHOSSID_MANIFEST_URL, { credentials: 'omit' });
		if (!response?.ok) return CHOSSID_FALLBACK_URL;
		const manifest = await response.json();
		const publicUrl = manifest?.assets?.canonicalChossid?.publicUrl;
		if (typeof publicUrl === 'string' && publicUrl.endsWith('/chossid.glb')) {
			return publicUrl;
		}
	} catch {
		// The manifest is a convenience, never a single point of failure:
		// the build's stable canonical copy carries the identical bytes.
	}
	return CHOSSID_FALLBACK_URL;
}
