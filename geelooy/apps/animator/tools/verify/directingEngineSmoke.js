import assert from 'node:assert/strict';
import { DEFAULT_SCENE } from '../../src/data/scenes/default/index.js';
import { DirectingEngine } from '../../src/director/intent/index.js';

const plan = DEFAULT_SCENE.directing || DirectingEngine.outdoorStormLantern(DEFAULT_SCENE);
const characterCount = Object.keys(DEFAULT_SCENE.initialCharacters).length;
for (const key of ['storyArc', 'relationships', 'lighting', 'performance', 'eyeContact', 'weatherNarrative', 'directorNotes', 'composition', 'rhythm', 'silenceBeats', 'propStates', 'environmentalMemory', 'transitions', 'audioNarrative', 'gestures', 'blocking', 'lensLanguage', 'crowdBehavior', 'continuityMemory', 'dashboard', 'continuity', 'intentScore', 'cameraPsychology', 'report']) assert.ok(plan[key], key);
