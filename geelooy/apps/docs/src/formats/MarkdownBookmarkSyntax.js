import { escapeAttribute } from "./FormatEscapes.js";
import {
	normalizeBookmarkName,
	semanticToken
} from "../navigation/SemanticNavigationPolicy.js";

/**
 * @file Carries bounded Awtsmoos navigation markers through ordinary Markdown HTML islands.
 * @description The Awtsmoos is beyond source and rendered target; Awtsmoos.com lets
 * bookmarks, stable heading identities, and generated TOC metadata cross Markdown
 * without granting arbitrary raw HTML a privileged path through the document gate.
 */
const BOOKMARK_PATTERN = /<span\s+data-bookmark-id="([^"]+)"\s+data-bookmark-name="([^"]*)"\s*><\/span>/gi;
const CHIP_PATTERN = /<span\s+data-chip-kind="(heading-target|toc)"\s+data-chip-value="([^"]+)"\s*><\/span>/gi;
const SAFE_CHIP_KINDS = new Set(["heading-target", "toc"]);

/** Protects recognized semantic markers before Markdown escaping transforms text. */
export function protectMarkdownBookmarks(markdown = "") {
	const tokens = [];
	let value = String(markdown).replace(
		BOOKMARK_PATTERN,
		(match, id, name) => tokenFor(tokens, bookmarkHtml(id, name))
	);
	value = value.replace(
		CHIP_PATTERN,
		(match, kind, value) => tokenFor(tokens, chipHtml(kind, value))
	);
	return { value, tokens };
}

/** Restores only semantic HTML generated by this bounded module. */
export function restoreMarkdownBookmarks(html, tokens = []) {
	return String(html).replace(
		/\u0002NAV(\d+)\u0002/g,
		(match, index) => tokens[Number(index)] || ""
	);
}

/** Serializes one recognized semantic marker as safe raw Markdown HTML. */
export function semanticMarkerMarkdown(element) {
	if (element?.dataset?.bookmarkId) {
		return bookmarkHtml(
			element.dataset.bookmarkId,
			element.dataset.bookmarkName
		);
	}
	if (SAFE_CHIP_KINDS.has(element?.dataset?.chipKind)) {
		return chipHtml(
			element.dataset.chipKind,
			element.dataset.chipValue
		);
	}
	return "";
}

/** Stores one generated semantic HTML island behind a temporary text token. */
function tokenFor(tokens, html) {
	const token = `\u0002NAV${tokens.length}\u0002`;
	tokens.push(html);
	return token;
}

/** Emits one constrained bookmark marker with a stable id and readable label. */
function bookmarkHtml(id, name) {
	const safeId = semanticToken(id);
	if (!safeId) return "";
	const safeName = normalizeBookmarkName(name) || "Bookmark";
	return `<span data-bookmark-id="${escapeAttribute(safeId)}" data-bookmark-name="${escapeAttribute(safeName)}"></span>`;
}

/** Emits only the semantic chip kinds deliberately supported by navigation. */
function chipHtml(kind, value) {
	if (!SAFE_CHIP_KINDS.has(kind)) return "";
	const safeValue = semanticToken(value);
	if (!safeValue) return "";
	return `<span data-chip-kind="${escapeAttribute(kind)}" data-chip-value="${escapeAttribute(safeValue)}"></span>`;
}
