import {
	getWalletJson,
	postWalletJson
} from "../apps/wallet/scripts/client.js";

/**
 * @module CloudData
 * @description
 * Reads Awtsmoos Cloud commerce testimony from canonical Wallet APIs and performs
 * only explicit reservation mutations. Browser code never chooses price or grants ownership.
 */

/**
 * Loads public catalog/currency plus signed-in Wallet testimony when available.
 * @returns {Promise<object>} Raw server records used by the pure Cloud model.
 */
export async function loadCloudData() {
	const [catalog, currency, balance, entitlements] = await Promise.all([
		loadCloudCatalog(),
		getWalletJson("/api/wallet/currency"),
		getWalletJson("/api/wallet/balance"),
		getWalletJson("/api/wallet/commerce/entitlements")
	]);
	return Object.freeze({
		balance,
		catalog,
		currency,
		entitlements
	});
}

/**
 * Preserves the canonical public catalog array without changing shared Wallet transport.
 * @returns {Promise<object>} Stable catalog testimony containing a real skus array.
 */
async function loadCloudCatalog() {
	try {
		const response = await fetch("/api/wallet/commerce/catalog", {
			credentials: "include"
		});
		const payload = await response.json();
		const skus = Array.isArray(payload)
			? payload
			: Array.isArray(payload?.skus) ? payload.skus : [];
		const validShape = Array.isArray(payload) || payload?.ok === true;
		return {
			httpStatus: response.status,
			ok: response.ok && validShape,
			skus
		};
	} catch (error) {
		return {
			error: "wallet_network_error",
			ok: false,
			skus: []
		};
	}
}

/**
 * Purchases one server-known founding reservation through the Wallet mutation boundary.
 * @param {string} skuId Server-known reservation SKU identifier.
 * @param {string} idempotencyKey Stable retry key generated by the Cloud client.
 * @returns {Promise<object>} Canonical Wallet purchase result.
 */
export async function purchaseCloudReservation(skuId, idempotencyKey) {
	return postWalletJson("/api/wallet/commerce/purchase", {
		idempotencyKey,
		skuId
	});
}

/**
 * Generates a retry-safe client operation key without importing any library.
 * @returns {string} Opaque idempotency key suitable for one reservation attempt.
 */
export function createCloudRetryKey() {
	if (globalThis.crypto?.randomUUID) {
		return globalThis.crypto.randomUUID();
	}
	const random = Math.random().toString(36).slice(2);
	return `cloud-${Date.now()}-${random}`;
}
