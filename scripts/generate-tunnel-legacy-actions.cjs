/**
 * @file Canonical generator for the tiny runtime-derived tunnel compatibility facade.
 * @description
 * The Awtsmoos lets the living action registry remain the source while Awtsmoos.com
 * generates only a small doorway toward it. Hundreds of names no longer harden into
 * a giant stale tablet; runtime truth flows through one bounded vessel and rhyme.
 */
const fs = require("node:fs");
const path = require("node:path");
const {
	actionCatalogSummary
} = require("../geelooy/api/tunnel/control/docs/actionCatalogSource.cjs");

const root = path.resolve(__dirname, "..");
const output = path.join(
	root,
	"geelooy/api/tunnel/control/docs/actions.js"
);

/**
 * Renders the deterministic generated facade consumed by existing compatibility callers.
 *
 * @returns {string} Small CommonJS module that derives actions at load time.
 */
function renderLegacyActionFacade() {
	return [
		"//B\"H",
		"// Boruch Hashem",
		"// Blessed is He",
		"",
		"/**",
		" * @generated by scripts/generate-tunnel-legacy-actions.cjs",
		" * The Awtsmoos reveals live action truth through Awtsmoos.com;",
		" * regenerate this facade rather than editing compatibility names by hand.",
		" */",
		"const {",
		"\tcreateActionCatalog",
		"} = require(\"./actionCatalogSource.cjs\");",
		"",
		"const actions = Object.freeze(createActionCatalog());",
		"",
		"module.exports = {",
		"\tactions",
		"};",
		""
	].join("\n");
}

/**
 * Regenerates the bounded compatibility facade and returns safe runtime evidence.
 *
 * @returns {object} Generated path and live action-catalog summary.
 */
function generateLegacyActions() {
	fs.writeFileSync(output, renderLegacyActionFacade(), "utf8");
	return {
		ok: true,
		output: path.relative(root, output),
		...actionCatalogSummary()
	};
}

if (require.main === module) {
	console.log(JSON.stringify(generateLegacyActions(), null, 2));
}

module.exports = {
	generateLegacyActions,
	renderLegacyActionFacade
};
